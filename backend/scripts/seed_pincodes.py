# Every row is filled the way the directory's own rows are (user, 2026-10-16): the bookkeeping
# columns below, one `token` per run (the directory's rows share their import's token), and a
# `pincodeUid` of PUI + the row's id (at least 3 digits) + the pincode - e.g. PUI016515571. One
# pincode serves several post offices, so a row is a duplicate only when its pincode, office,
# district and state all match one already there.
SEEDED_BY = "System"
BOOKKEEPING = {"isRead": "Yes", "status": "Approved", "remarks": "Verified", "securityDetails": "Secured", "masterRemarks": "Updated"}


def pincode_uid(row_id: int, pincode: str) -> str:
    return f"PUI{row_id:03d}{pincode}"


def seed_pincodes():
    token = f"{secrets.randbelow(90000) + 10000}"
    with common_engine.begin() as conn:
        existing_rows = conn.execute(
            text("SELECT pincode, officeName, district, stateName FROM pincode")
        ).fetchall()
        existing_keys = {
            (row[0], (row[1] or "").upper(), (row[2] or "").upper(), (row[3] or "").upper())
            for row in existing_rows
        }

        inserted = 0
        skipped = 0

        for entry in PINCODE_ENTRIES:
            key = (
                entry["pincode"],
                entry["officeName"].upper(),
                entry["district"].upper(),
                entry["stateName"].upper(),
            )
            if key in existing_keys:
                skipped += 1
                continue

            row_id = conn.execute(
                text(
                    """
                    INSERT INTO pincode (
                        pincodeUid, circleName, regionName, divisionName, officeName, pincode, officeType, delivery,
                        district, stateName, latitude, longitude,
                        updatedBy, updationOn, isRead, token, timestamp, status, remarks, securityDetails, masterRemarks
                    ) VALUES (
                        :placeholder, :circleName, :regionName, :divisionName, :officeName, :pincode, :officeType, :delivery,
                        :district, :stateName, :latitude, :longitude,
                        :updatedBy, NOW(), :isRead, :token, NOW(), :status, :remarks, :securityDetails, :masterRemarks
                    )
                    """
                ),
                {
                    # Unique stand-in until the row's id is known (replaced just below, same transaction).
                    "placeholder": f"PUI-NEW-{secrets.token_hex(6)}",
                    "circleName": entry["circleName"],
                    "regionName": entry["regionName"],
                    "divisionName": entry["divisionName"],
                    "officeName": entry["officeName"],
                    "pincode": entry["pincode"],
                    "officeType": entry["officeType"],
                    "delivery": entry["delivery"],
                    "district": entry["district"],
                    "stateName": entry["stateName"],
                    "latitude": entry["latitude"],
                    "longitude": entry["longitude"],
                    "updatedBy": SEEDED_BY,
                    "token": token,
                    **BOOKKEEPING,
                },
            ).lastrowid
            # The ID needs the row's own id, known only once it is inserted.
            conn.execute(
                text("UPDATE pincode SET pincodeUid = :uid WHERE id = :id"),
                {"uid": pincode_uid(row_id, entry["pincode"]), "id": row_id},
            )
            existing_keys.add(key)
            inserted += 1

        print(f"Pincode seeding complete: {inserted} inserted, {skipped} skipped (token {token}).")


